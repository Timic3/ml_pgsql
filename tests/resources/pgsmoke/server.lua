addEventHandler("onResourceStart", resourceRoot, function()
    print("[smoke] module version", pgVersion())
    local db, err = pgConnect("host=postgres user=mta password=mta dbname=mta")
    print("[smoke] connect", tostring(db), err)
    local rows, e, n = pgQuerySync(db, "SELECT 1 AS one, $1::text AS t, NULL AS n, true AS b, 1.5::float8 AS f, ARRAY[1,2,3] AS arr, 9007199254740993::int8 AS big", "hello")
    print("[smoke] sync", rows and #rows, e, n)
    for k, v in pairs(rows[1]) do print("   ", k, type(v), type(v) == "table" and table.concat(v, ",") or tostring(v)) end
    pgQuery(db, function(r, err, aff) print("[smoke] async cb", r and #r, err, aff, r and r[1].x) end, "SELECT $1::int + 1 AS x", 41)
    db:query(function(r, err, sqlstate) print("[smoke] method cb error", r, err, sqlstate) end, "SELECT 1/0")
    pgExec(db, "SELECT * FROM nonexistent_table")
    local co = coroutine.create(function()
        local r, err = pgQueryAwait(db, "SELECT pg_sleep(0.1), 'awaited' AS v")
        print("[smoke] await", r and r[1].v, err)
        local res, err2 = pgTransactionAwait(db, { "CREATE TEMP TABLE t(x int)", {"INSERT INTO t VALUES ($1), ($2)", 1, 2}, "SELECT sum(x) AS s FROM t" })
        print("[smoke] tx", res and res[3][1].s, err2)
        print("[smoke] stats", inspect(pgStats(db)))
        setTimer(function() shutdown("smoke done") end, 300, 1)
    end)
    coroutine.resume(co)
end)
